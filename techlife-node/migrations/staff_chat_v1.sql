BEGIN;

-- Composite user key allows staff-chat rows to enforce tenant ownership.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_tenant_id_id
    ON public.users (tenant_id, id);

CREATE TABLE IF NOT EXISTS public.staff_conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL
        REFERENCES public.tenants(id) ON DELETE CASCADE,

    conversation_type VARCHAR(20) NOT NULL
        CHECK (conversation_type IN ('direct', 'group', 'announcement')),

    audience_type VARCHAR(20),
    audience_id UUID,
    title VARCHAR(200),

    created_by_user_id UUID
        REFERENCES public.users(id) ON DELETE SET NULL,

    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT staff_conversations_tenant_id_id_key
        UNIQUE (tenant_id, id),

    CONSTRAINT staff_conversations_audience_type_check
        CHECK (
            audience_type IS NULL OR
            audience_type IN ('direct', 'selected', 'group', 'queue', 'campaign')
        ),

    CONSTRAINT staff_conversations_audience_id_check
        CHECK (
            (audience_type IS NULL AND audience_id IS NULL)
            OR (audience_type IN ('direct', 'selected') AND audience_id IS NULL)
            OR (audience_type IN ('group', 'queue', 'campaign') AND audience_id IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS public.staff_conversation_members (
    tenant_id UUID NOT NULL,
    conversation_id UUID NOT NULL,
    user_id UUID NOT NULL,

    member_role VARCHAR(20) NOT NULL DEFAULT 'member'
        CHECK (member_role IN ('owner', 'member')),

    last_read_message_id BIGINT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (conversation_id, user_id),

    CONSTRAINT staff_members_tenant_conversation_user_key
        UNIQUE (tenant_id, conversation_id, user_id),

    CONSTRAINT staff_members_conversation_fk
        FOREIGN KEY (tenant_id, conversation_id)
        REFERENCES public.staff_conversations(tenant_id, id)
        ON DELETE CASCADE,

    CONSTRAINT staff_members_user_fk
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES public.users(tenant_id, id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.staff_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    conversation_id UUID NOT NULL,
    sender_user_id UUID,
    body TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT staff_messages_body_check
        CHECK (char_length(btrim(body)) BETWEEN 1 AND 4000),

    CONSTRAINT staff_messages_tenant_id_key
        UNIQUE (tenant_id, id),

    CONSTRAINT staff_messages_conversation_fk
        FOREIGN KEY (tenant_id, conversation_id)
        REFERENCES public.staff_conversations(tenant_id, id)
        ON DELETE CASCADE,

    CONSTRAINT staff_messages_sender_fk
        FOREIGN KEY (sender_user_id)
        REFERENCES public.users(id)
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.staff_message_reads (
    tenant_id UUID NOT NULL,
    message_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    read_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (message_id, user_id),

    CONSTRAINT staff_message_reads_message_fk
        FOREIGN KEY (tenant_id, message_id)
        REFERENCES public.staff_messages(tenant_id, id)
        ON DELETE CASCADE,

    CONSTRAINT staff_message_reads_user_fk
        FOREIGN KEY (tenant_id, user_id)
        REFERENCES public.users(tenant_id, id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_staff_conversations_tenant_updated
    ON public.staff_conversations (tenant_id, updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_staff_members_user_active
    ON public.staff_conversation_members
       (tenant_id, user_id, is_active, conversation_id);

CREATE INDEX IF NOT EXISTS idx_staff_messages_conversation
    ON public.staff_messages (tenant_id, conversation_id, id);

CREATE INDEX IF NOT EXISTS idx_staff_message_reads_user
    ON public.staff_message_reads (tenant_id, user_id, read_at DESC);

COMMIT;
